-- Comptabilité M57, amortissement, services gestionnaires, sorties d'inventaire.
-- Idempotent : peut être rejoué sans risque.

-- Services gestionnaires (organigramme simple : direction > service)
CREATE TABLE IF NOT EXISTS services (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  code text UNIQUE,
  parent_id integer REFERENCES services(id) ON DELETE SET NULL,
  manager_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS services_parent_idx ON services(parent_id);
ALTER TABLE services ENABLE ROW LEVEL SECURITY;

-- Compte d'imputation par défaut de la catégorie (nomenclature M57, ex. 2183, 2184)
ALTER TABLE categories ADD COLUMN IF NOT EXISTS account_code text;

-- Données comptables et administratives des biens
ALTER TABLE assets ADD COLUMN IF NOT EXISTS service_id integer REFERENCES services(id) ON DELETE SET NULL;
ALTER TABLE assets ADD COLUMN IF NOT EXISTS inventory_number text;          -- n° d'inventaire comptable (état de l'actif)
ALTER TABLE assets ADD COLUMN IF NOT EXISTS account_code text;              -- compte d'imputation (surcharge la catégorie)
ALTER TABLE assets ADD COLUMN IF NOT EXISTS acquisition_mode text NOT NULL DEFAULT 'achat';
ALTER TABLE assets ADD COLUMN IF NOT EXISTS fiscal_year integer;            -- exercice d'acquisition
ALTER TABLE assets ADD COLUMN IF NOT EXISTS mandate_number text;            -- n° de mandat
ALTER TABLE assets ADD COLUMN IF NOT EXISTS invoice_number text;            -- n° de facture
ALTER TABLE assets ADD COLUMN IF NOT EXISTS contract_number text;           -- n° de marché public
ALTER TABLE assets ADD COLUMN IF NOT EXISTS depreciation_years integer;     -- durée (surcharge la catégorie)
ALTER TABLE assets ADD COLUMN IF NOT EXISTS commissioning_date date;        -- date de mise en service (début de l'amortissement)
