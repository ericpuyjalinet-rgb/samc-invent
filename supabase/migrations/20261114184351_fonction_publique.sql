-- Nouveau statut « sorti » : bien sorti de l'inventaire après décision
ALTER TABLE assets DROP CONSTRAINT IF EXISTS assets_status_check;
ALTER TABLE assets ADD CONSTRAINT assets_status_check
  CHECK (status IN ('en_service','en_stock','en_reparation','reforme','perdu','sorti'));

-- Sorties d'inventaire (réforme) : proposition → décision → sortie
CREATE TABLE IF NOT EXISTS disposals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id integer NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'proposee' CHECK (status IN ('proposee','validee','annulee')),
  reason text NOT NULL CHECK (reason IN ('obsolescence','panne','vol','perte','destruction','cession','don','transfert','autre')),
  reason_details text,
  proposed_by integer REFERENCES users(id) ON DELETE SET NULL,
  proposed_at timestamptz NOT NULL DEFAULT now(),
  decision_type text CHECK (decision_type IN ('certificat_administratif','decision','deliberation')),
  decision_number text,
  decision_date date,
  exit_date date,
  sale_price double precision,
  beneficiary text,
  gross_value double precision,        -- valeur brute figée à la sortie
  net_book_value double precision,     -- valeur nette comptable figée à la sortie
  validated_by integer REFERENCES users(id) ON DELETE SET NULL,
  validated_at timestamptz,
  previous_status text,               -- statut du bien avant la proposition (rétabli en cas d'annulation)
  notes text,
  campaign_id integer REFERENCES campaigns(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS disposals_asset_idx ON disposals(asset_id);
CREATE INDEX IF NOT EXISTS disposals_status_idx ON disposals(status);
CREATE INDEX IF NOT EXISTS disposals_proposed_by_idx ON disposals(proposed_by);
CREATE INDEX IF NOT EXISTS disposals_validated_by_idx ON disposals(validated_by);
CREATE INDEX IF NOT EXISTS disposals_campaign_idx ON disposals(campaign_id);
-- Une seule proposition en cours par bien
CREATE UNIQUE INDEX IF NOT EXISTS disposals_one_open_idx ON disposals(asset_id) WHERE status = 'proposee';
ALTER TABLE disposals ENABLE ROW LEVEL SECURITY;
