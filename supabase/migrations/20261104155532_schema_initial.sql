-- SAMC Invent — schéma initial (PostgreSQL / Supabase)
-- Idempotent : peut être rejoué sans risque.

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'agent' CHECK (role IN ('admin','gestionnaire','agent')),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON users (lower(email));

CREATE TABLE IF NOT EXISTS sites (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  address text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS locations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  code text UNIQUE,
  building text,
  floor text,
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS locations_site_idx ON locations(site_id);

CREATE TABLE IF NOT EXISTS categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  family text NOT NULL DEFAULT 'autre' CHECK (family IN ('informatique','mobilier','autre')),
  depreciation_years integer,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS assets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  label text NOT NULL,
  category_id integer REFERENCES categories(id) ON DELETE SET NULL,
  brand text,
  model text,
  serial_number text,
  location_id integer REFERENCES locations(id) ON DELETE SET NULL,
  assigned_to text,
  status text NOT NULL DEFAULT 'en_service'
    CHECK (status IN ('en_service','en_stock','en_reparation','reforme','perdu')),
  condition text NOT NULL DEFAULT 'bon'
    CHECK (condition IN ('neuf','bon','moyen','mauvais','hs')),
  purchase_date date,
  purchase_price double precision,
  supplier text,
  warranty_end date,
  notes text,
  photo text,
  last_seen_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS assets_location_idx ON assets(location_id);
CREATE INDEX IF NOT EXISTS assets_category_idx ON assets(category_id);
CREATE INDEX IF NOT EXISTS assets_code_lower_idx ON assets(lower(code));
CREATE INDEX IF NOT EXISTS assets_serial_lower_idx ON assets(lower(serial_number));

CREATE TABLE IF NOT EXISTS asset_history (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id integer NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  action text NOT NULL,
  details text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS asset_history_asset_idx ON asset_history(asset_id);
CREATE INDEX IF NOT EXISTS asset_history_user_idx ON asset_history(user_id);

CREATE TABLE IF NOT EXISTS campaigns (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text,
  status text NOT NULL DEFAULT 'brouillon' CHECK (status IN ('brouillon','en_cours','cloturee')),
  start_date date,
  end_date date,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz
);
CREATE INDEX IF NOT EXISTS campaigns_created_by_idx ON campaigns(created_by);

-- Périmètre de la campagne (vide = toutes les salles)
CREATE TABLE IF NOT EXISTS campaign_locations (
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  location_id integer NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
  PRIMARY KEY (campaign_id, location_id)
);
CREATE INDEX IF NOT EXISTS campaign_locations_location_idx ON campaign_locations(location_id);

-- Instantané des équipements attendus au lancement
CREATE TABLE IF NOT EXISTS campaign_expected (
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  asset_id integer NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  location_id integer,
  PRIMARY KEY (campaign_id, asset_id)
);
CREATE INDEX IF NOT EXISTS campaign_expected_asset_idx ON campaign_expected(asset_id);

-- Relevés terrain (application mobile)
CREATE TABLE IF NOT EXISTS scans (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_uuid text NOT NULL UNIQUE,
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  asset_id integer REFERENCES assets(id) ON DELETE SET NULL,
  scanned_code text,
  location_id integer REFERENCES locations(id) ON DELETE SET NULL,
  result text NOT NULL CHECK (result IN ('trouve','deplace','inconnu')),
  condition text,
  comment text,
  photo text,
  unknown_label text,
  unknown_category_id integer REFERENCES categories(id) ON DELETE SET NULL,
  resolved_asset_id integer REFERENCES assets(id) ON DELETE SET NULL,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  scanned_at timestamptz NOT NULL,
  synced_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS scans_campaign_idx ON scans(campaign_id);
CREATE INDEX IF NOT EXISTS scans_asset_idx ON scans(asset_id);
CREATE INDEX IF NOT EXISTS scans_location_idx ON scans(location_id);
CREATE INDEX IF NOT EXISTS scans_user_idx ON scans(user_id);
CREATE INDEX IF NOT EXISTS scans_resolved_idx ON scans(resolved_asset_id);
CREATE INDEX IF NOT EXISTS scans_unknown_cat_idx ON scans(unknown_category_id);

CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value text
);

